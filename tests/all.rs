//! Every test file but those listed in Cargo.toml as their own `[[test]]`, as one test binary: one link of the
//! engine instead of one per file (269 of them took most of a rebuild). Each file is a module, so its tests are named
//! `<file>::<test>` (`cargo nextest run -E 'test(/^pgdiff::/)'`, or `cargo test --test all -- pgdiff::`).
//!
//! Under plain `cargo test` all of them share one process (nextest gives each test its own): a file that sets the
//! process's environment (CHRONOS_WORK_MEM, CHRONOS_SOURCE_URL, ...), which the engine may read once and keep, is a
//! binary of its own, not a module here.

/// The name libtest gives test `$n` of the module calling it, for a test that runs its own binary again on just that
/// test (`--exact`): its module's path, less the crate's.
macro_rules! test_name {
    ($n:expr) => {
        match module_path!().split_once("::") {
            Some((_, m)) => format!("{m}::{}", $n),
            None => $n.to_string(),
        }
    };
}

